public class SequenciaV4 {
	public static void main (String [] args) {
		for (int i = 1; i <= 10; i++) {
			switch (i) {
				case 1:
					System.out.println(i + ", " + "2 3 4 5 6 7 8 9 10");
					break;
				case 2:
					System.out.println(i + ", " + "3 4 5 6 7 8 9 10");
					break;
				case 3:
					System.out.println(i + ", " + "4 5 6 7 8 9 10");
					break;
				case 4:
					System.out.println(i + ", " + "5 6 7 8 9 10");
					break;
				case 5:
					System.out.println(i + ", " + "6 7 8 9 10");
					break;
				case 6:
					System.out.println(i + ", " + "7 8 9 10");
					break;
				case 7:
					System.out.println(i + ", " + "8 9 10");
					break;
				case 8:
					System.out.println(i + ", " + "9 10");
					break;
				case 9:
					System.out.println(i + ", " + "10");
					break;
				case 10:
					System.out.print(i + ", " + " ");
					break;
				}
				}
			}
		}
